import 'dart:async';
import 'dart:typed_data';

enum BleConnectionState {
  disconnected,
  scanning,
  connecting,
  connected,
  mockMode,
  error,
}

class BleService {
  BleConnectionState _connectionState = BleConnectionState.mockMode;
  final int _batteryLevel = 92;
  bool _isMockMode = true;

  final StreamController<BleConnectionState> _stateController =
      StreamController<BleConnectionState>.broadcast();

  BleConnectionState get connectionState => _connectionState;
  int get batteryLevel => _batteryLevel;
  bool get isMockMode => _isMockMode;
  Stream<BleConnectionState> get stateStream => _stateController.stream;

  void setMockMode(bool enabled) {
    _isMockMode = enabled;
    _connectionState = enabled ? BleConnectionState.mockMode : BleConnectionState.disconnected;
    _stateController.add(_connectionState);
  }

  Future<void> startScan() async {
    _connectionState = BleConnectionState.scanning;
    _stateController.add(_connectionState);

    await Future.delayed(const Duration(seconds: 1));

    _connectionState = _isMockMode ? BleConnectionState.mockMode : BleConnectionState.connected;
    _stateController.add(_connectionState);
  }

